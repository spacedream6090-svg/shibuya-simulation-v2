def approx_tokens(s):
    """日本語の概算トークン数。1.30文字/トークンの粗い係数(答申§4-3=実測を推奨)。
    真値は run_probe.py が API の usage.prompt_tokens として記録する。"""
    return int(round(len(s) / 1.30))


def build():
    items = []

    for fam, rows, spec, b0lvl in (
            (1, F1, SPEC_F1, "mid"), (2, F2, SPEC_F2, "mid"), (3, F3, SPEC_F3, "qa"),
            (4, F4, SPEC_F4, "mid"), (5, F5, SPEC_F5, "mid")):
        for r in rows:
            items.append(dict(
                id=r["id"], family=fam, title=r["title"],
                system_block=b0(b0lvl, spec), observation=r["obs"], question=r["q"],
                output_spec=spec, expected=r["expected"], judge="machine",
                max_tokens=MAXTOK[fam], temperature=0.0, repeats=1,
                stability_subset=(fam in (2, 4)),
                family6_variants=None))

    for n, sc in enumerate(SCENES, 1):
        variants = {}
        for v in ("v0", "v1", "full"):
            obs = render_scene(sc, v)
            sysb = b0(TRIM[v]["b0"], SPEC_F6)
            variants[v] = dict(
                salience_tier=sc["tier"], system_block=sysb, observation=obs,
                obs_chars=len(obs), sys_chars=len(sysb),
                approx_tokens=approx_tokens(sysb + "\n" + obs + "\n" + sc["q"]))
        items.append(dict(
            id="F6-%02d" % n, family=6, title=sc["title"],
            system_block=variants["v1"]["system_block"],
            observation=variants["v1"]["observation"],
            question=sc["q"], output_spec=SPEC_F6,
            expected=dict(
                allowed_actions=sc["allowed"], constraints=[], gold_answer=None,
                termination_signal=None, consistency_pair_id=None,
                scene_id=sc["sid"], salience_tier=sc["tier"],
                driver_channel=sc["driver"], driver_kept_in=sc["driver_kept"],
                predicted_disagreement=sc["pred_dis"]),
            judge="machine", max_tokens=MAXTOK[6], temperature=0.0, repeats=1,
            stability_subset=False,
            salience_tier=sc["tier"],
            family6_variants=variants))
    return items


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "probes.jsonl"))
    a = ap.parse_args()

    items = build()
    lines = [json.dumps(it, ensure_ascii=False, sort_keys=True) for it in items]
    body = "\n".join(lines) + "\n"
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)

    h = hashlib.sha256(body.encode("utf-8")).hexdigest()
    with open(os.path.join(os.path.dirname(a.out), "item_set_hash.txt"), "w",
              encoding="utf-8", newline="\n") as f:
        f.write("item_set_hash(sha256 of probes.jsonl) = %s\nn_items = %d\n" % (h, len(items)))

    from collections import Counter
    fam = Counter(i["family"] for i in items)
    print("wrote %s (%d items)" % (a.out, len(items)))
    print("families:", dict(sorted(fam.items())))
    tier = Counter(i["salience_tier"] for i in items if i["family"] == 6)
    print("family6 tiers:", dict(tier))
    print("family6 predicted-disagreement scenes:",
          sum(1 for i in items if i["family"] == 6 and i["expected"]["predicted_disagreement"]))
    for v in ("v1", "v0", "full"):
        toks = [i["family6_variants"][v]["approx_tokens"] for i in items if i["family"] == 6]
        print("  %-4s approx_tokens: min=%d mean=%d max=%d (target v1=1300 v0=1800 full=3000)"
              % (v, min(toks), sum(toks) // len(toks), max(toks)))
    print("item_set_hash =", h)


if __name__ == "__main__":
    main()
