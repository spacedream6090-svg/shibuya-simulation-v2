"""R-111 の [再計算] の値を出す(標準ライブラリだけ・入力は答申 §0 の原典の数値の写し)。

使い方: python docs/research/scripts/r111/recompute.py
値の出どころは答申 docs/research/v2-r111-time-perception-decision-time-speech-rate.md の §0 の番号。
"""


def pct(a: float, b: float) -> float:
    """a が b より何 % 大きいか。"""
    return (a / b - 1.0) * 100.0


def main() -> None:
    print("== F1 経過時間の実感 ==")
    # #1 Watkins 2011 学位論文 表 3.1(従来の情報で来た人 544 人)
    pw, mw = 6.19, 5.36
    print(f"#1 待ちの実感/実測 = {pw}/{mw} = {pw / mw:.3f}(+{pct(pw, mw):.1f}%)差 {pw - mw:.2f} 分")
    # #1 表 3.5 の回帰 PW = 1.9 + 0.72*MW + ...(他の項を 0 と置いた形だけ。推測の扱い)
    for m in (2, 5, 10, 15):
        p = 1.9 + 0.72 * m
        print(f"   MW={m:>2} 分 -> 切片と傾きだけの PW={p:.2f}(比 {p / m:.2f})")
    print(f"   切片と傾きだけで PW=MW になる点 = {1.9 / (1 - 0.72):.1f} 分(他の項で動く)")
    # #4 Peer 2014: 比の中央値 1.55・平均 1.58(本文の値をそのまま)
    # #3 Kelly 2013: +4.4 分 (+28.6%) -> 平均の GPS の所要時間の逆算(推測)
    print(f"#3 +4.4 分が +28.6% なら、元の平均は約 {4.4 / 0.286:.1f} 分(逆算・推測)")
    # #5 van Exel & Rietveld 2010: 車 60 分・公共交通の実感 117 分
    print(f"#5 117/60 = {117 / 60:.2f}(車の時間に対する公共交通の見積り)")
    # #8 Block & Zakay 1997: 比 0.90〜0.92(予期)・0.78〜0.90(振り返り)
    print("#8 予期/振り返り の比 = 1.02(短い)・1.17(中〜長い)= 本文の値")

    print("== B8 判断にかける時間 ==")
    # #19 Krajbich & Rangel 2011: 難しさ 1 段で -145 ms
    print("#19 3 択の食べ物: 評価の差 1 段あたり 145 ms 短くなる(本文の値)")
    # #20 Milosavljevic 2010 図 3B: d=1 と d=4 の差
    print(f"#20 LTP: 616->517 ms = {pct(517, 616):.1f}% / HTP: 433->401 ms = {pct(401, 433):.1f}%")
    # #22 Dickson & Sawyer: 12 秒・1.2 銘柄
    print("#22 売り場での 1 品の選択 = 平均 12 秒(MSI の要約)")

    print("== C4 話す速さ ==")
    # #38 石本 2024: 平均モーラ長
    for name, d in (("平均", 0.151), ("最速 T013", 0.124), ("最遅 K002", 0.198)):
        print(f"#38 {name}: {d} 秒/モーラ -> {1 / d:.2f} モーラ/秒")
    print(f"#38 最遅/最速 = {0.198 / 0.124:.2f} 倍")
    # #41 Coupé 2019: 話者の σ 0.57・文章の σ 0.11・平均 6.63 音節/秒
    print(f"#41 話者の σ/平均 = {0.57 / 6.63 * 100:.1f}% ・ 文章の σ/平均 = {0.11 / 6.63 * 100:.1f}%(全言語をまとめた平均で割った目安・推測)")
    # #42 Quené 2005: 話者間 σ2=232・話者内 σ2=8601(ms^2)・平均 223 ms
    print(f"#42 話者間 σ = {232 ** 0.5:.1f} ms ・ 話者内 σ = {8601 ** 0.5:.1f} ms ・ 話者内 CV = {8601 ** 0.5 / 223:.2f}")
    print(f"#42 年齢 25->65 歳: 40*0.5/223 = {40 * 0.5 / 223 * 100:.1f}%")
    # #44 Yuan 2006 表 2
    print(f"#44 英語 親しい/知らない = 214/193 = +{pct(214, 193):.1f}% ・ 中国語 247/228 = +{pct(247, 228):.1f}%")
    print(f"#44 話題で 152->170 wpm = +{pct(170, 152):.1f}%")


