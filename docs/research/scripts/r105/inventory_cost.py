"""R-105 (iii): 品目つきの持ち物と、原因つきの書き換えの記録の容量の見積り(推測の前提つき)。

前提はすべて本スクリプトの定数に書く。出典のある値は注に答申の番号を書く。
- N_FULL = 390_067: v2 の実データ規模(src/shibuya/economy/goods.py の注「390,067 体」)。
- 金の帳簿の生ログの実測 4.07 行/体/日(R-72・10b の材料 §3-4)。
- 物の配達ログの宣言 2.0 行/体/日・16 B/行(goods.py の注)。
それ以外(1 人が持つ品目の数・物の移動の回数・行の欄)は推測。
"""

N_FULL = 390_067
N_SMALL = 5_000

def mb(x):
    return x / 1e6

print("== 持ち物の表(状態) ==")
for n in (N_SMALL, N_FULL):
    for k in (5, 20, 50):           # 1 人が持つ品目の種類の数(推測)
        sparse8 = n * k * 8          # 体 u32 + 品目 u16 + 数 u16
        sparse12 = n * k * 12        # + 持ち主 u32(持っている人と持ち主を分ける)
        print(f"N={n:>7} K={k:>2}: 疎 8B={mb(sparse8):8.1f} MB  疎 12B(持ち主つき)={mb(sparse12):8.1f} MB")
for n in (N_SMALL, N_FULL):
    for s in (100, 1_000, 10_000):  # 品目の種類の総数(推測)
        dense = n * s * 1            # uint8 の密な表
        print(f"N={n:>7} S={s:>6}: 密 1B={mb(dense):10.1f} MB")

print("== 書き換えの記録(1 日) ==")
ROW_5W1H = 48  # 時刻8+誰4+出す側4+入る側4+品目4+数4+場所4+原因の種類1+原因 ID 8+理由の参照4=45→48(推測)
for n in (N_SMALL, N_FULL):
    money = n * 4.07 * 24            # 実測 4.07 行/体/日 × 24 B/行(R-72)
    print(f"N={n:>7}: 今の金の生ログ 4.07 行×24B = {mb(money):7.1f} MB/日")
    for g in (4.07, 10, 30):          # 1 体 1 日の書き換えの行数(推測。4.07 は金の実測)
        print(f"   行数 {g:>5}/体/日 × {ROW_5W1H}B = {mb(n*g*ROW_5W1H):8.1f} MB/日  30 日={mb(n*g*ROW_5W1H*30)/1e3:6.2f} GB")
