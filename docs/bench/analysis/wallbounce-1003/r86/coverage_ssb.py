def main(src: str, dst: str) -> None:
    d = json.loads(Path(src).read_text(encoding="utf-8"))
    small = [i for i in d["items"] if i["level"] == "小"]
    assert len(small) == 90 and set(MAP) == {i["code"] for i in small}, (len(small), set(MAP) ^ {i["code"] for i in small})
    rows = []
    for it in small:
        cov, r, s, word, note = MAP[it["code"]]
        m = 0 if it["minutes"] in ("-", None) else int(it["minutes"])
        rows.append({"code": it["code"], "name": it["name"], "minutes": m, "cov": cov, "r": r, "s": s,
                     "w": round(m * r * (1 + s), 2), "v2": word, "note": note})
    from collections import Counter
    cnt = Counter(r["cov"] for r in rows)
    mins = Counter()
    for r in rows:
        mins[r["cov"]] += r["minutes"]
    absent = sorted([r for r in rows if r["cov"] == "無い"], key=lambda x: -x["w"])
    near = sorted([r for r in rows if r["cov"] == "近い"], key=lambda x: -x["w"])
    out = {"source": d["source"], "formula": "w = minutes * r * (1 + s)(推測・expedient)", "counts": dict(cnt),
           "minutes_by_cov": dict(mins), "absent_ranked": absent, "near_ranked": near, "rows": rows}
    Path(dst).write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8", newline="\n")
    print(dict(cnt), dict(mins))
    for r in absent[:15]:
        print("無い", r["code"], r["name"], r["minutes"], r["r"], r["s"], r["w"])
    for r in near[:12]:
        print("近い", r["code"], r["name"], r["minutes"], r["r"], r["s"], r["w"])


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
